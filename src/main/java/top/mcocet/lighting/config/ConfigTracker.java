package top.mcocet.lighting.config;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;
import top.mcocet.lighting.event.EventBus;
import top.mcocet.lighting.event.ModConfigLoadEvent;
import top.mcocet.lighting.loader.LoaderConfig;
import top.mcocet.lighting.loader.ModContainer;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Mod 配置加载器——对应 FML 的 {@code ConfigTracker}。
 * <p>
 * 骨架阶段的配置模型(TOML-lite,核心语义与 FML 一致):
 * <ul>
 *   <li>每个 Mod 一份通用配置 {@code config/<modid>-common.toml};</li>
 *   <li>首次运行时自动生成带注释的默认文件(对应 FML 的 spec 默认值落盘);</li>
 *   <li>解析支持 {@code key=value} 行与 {@code [section]} 分组(扁平化为 {@code section.key});</li>
 *   <li>加载完成后按 Mod 发布 {@link ModConfigLoadEvent},并可按 key 查询。</li>
 * </ul>
 * client/server 分侧配置与热重载在接入真实游戏环境后扩展。
 */
public final class ConfigTracker {

    private static final Logger LOGGER = LogManager.getLogger(ConfigTracker.class);

    /** 默认配置文件内容(首次启动生成) */
    private static final String DEFAULT_COMMON_CONFIG = """
            # Generated by Lighting on first launch (common configuration for this mod).
            # Edit values and restart; keys are exposed to the mod through LightingLoader.config().
            enabled=true
            """;

    private final Path configDir;
    private final Map<String, Map<String, String>> valuesByMod = new ConcurrentHashMap<>();

    public ConfigTracker(LoaderConfig config) {
        this.configDir = config.configDir();
    }

    /**
     * 加载全部 Mod 的通用配置(由加载管线经
     * {@code ModWorkManager.runInitTask("Config loading")} 调用)。
     *
     * @return 实际加载的配置文件数量
     */
    public int loadAll(List<ModContainer> mods, EventBus eventBus) {
        int loaded = 0;
        for (ModContainer mod : mods) {
            loaded += loadOne(mod, eventBus);
        }
        LOGGER.info("Config loading finished: {} file(s) under {}", loaded, configDir);
        return loaded;
    }

    private int loadOne(ModContainer mod, EventBus eventBus) {
        Path file = configDir.resolve(mod.id() + "-common.toml");
        try {
            Files.createDirectories(configDir);
            if (!Files.isRegularFile(file)) {
                Files.writeString(file, DEFAULT_COMMON_CONFIG, StandardCharsets.UTF_8);
            }
            Map<String, String> values = parse(file);
            valuesByMod.put(mod.id(), values);
            eventBus.post(new ModConfigLoadEvent(mod.id(), file, values.size()));
            return 1;
        } catch (IOException e) {
            LOGGER.warn("Failed to load config for {}: {}", mod.id(), e.toString());
            return 0;
        }
    }

    /** TOML-lite 解析:{@code key=value} 行 + {@code [section]} 分组,其余行忽略 */
    private static Map<String, String> parse(Path file) throws IOException {
        Map<String, String> values = new LinkedHashMap<>();
        String section = "";
        for (String rawLine : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            String line = rawLine.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            if (line.startsWith("[") && line.endsWith("]")) {
                section = line.substring(1, line.length() - 1).trim() + ".";
                continue;
            }
            int eq = line.indexOf('=');
            if (eq <= 0) {
                continue;
            }
            String key = section + line.substring(0, eq).trim();
            String value = line.substring(eq + 1).trim();
            if (value.length() >= 2 && value.startsWith("\"") && value.endsWith("\"")) {
                value = value.substring(1, value.length() - 1);
            }
            values.put(key, value);
        }
        return values;
    }

    /** 按 key 查询配置项(如 {@code enabled} 或 {@code section.key}) */
    public Optional<String> value(String modId, String key) {
        Map<String, String> values = valuesByMod.get(modId);
        return values == null ? Optional.empty() : Optional.ofNullable(values.get(key));
    }

    /** 某 Mod 的全部配置项(只读) */
    public Map<String, String> values(String modId) {
        Map<String, String> values = valuesByMod.get(modId);
        return values == null ? Map.of() : Collections.unmodifiableMap(values);
    }
}
